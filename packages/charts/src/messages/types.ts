/**
 * Typed string catalogue for `@negaresh/charts` (D-94).
 * Chart components never hard-code visible strings; they read from `ChartMessagesProvider`
 * (defaulting to `faChartMessages`) or an optional per-chart `messages` prop.
 */
export interface ChartMessages {
  /** Native disclosure trigger label to expand/collapse the accessible data table. */
  dataTableToggle: string;
  /** Accessible caption fallback when a chart table omits an explicit caption. */
  dataTableCaption: string;
  /** Legend region accessible label. */
  legendLabel: string;
  /** Loading status text for screen readers. */
  loadingChart: string;
  /** Default empty-state title when no data points are provided. */
  emptyTitle: string;
  /** Default empty-state description. */
  emptyDescription: string;
  /** Default error-state title. */
  errorTitle: string;
  /** Default error-state description. */
  errorDescription: string;
  /** Retry button label in error state. */
  retry: string;
  /** Default active-point hint shown before keyboard/pointer inspection. */
  inspectHint: string;
  /** Screen-reader / readout phrasing for a point with confidence interval. */
  intervalReadout: (label: string, value: string, low?: string, high?: string, band?: string) => string;
  /** Screen-reader / readout phrasing for a series point. */
  pointReadout: (series: string, category: string, value: string) => string;
  /** Screen-reader / readout phrasing for a single-series bar/axis point. */
  singlePointReadout: (category: string, value: string) => string;
  /** Default table column headers generated by helper builders. */
  columnCategory: string;
  columnScale: string;
  columnValue: string;
  columnInterval: string;
  columnBand: string;
  columnSeries: string;
  /** Range phrasing («۶۲ تا ۷۴»). */
  rangeBetween: (low: string, high: string) => string;
  /** Missing data cell placeholder («—»). */
  missingValue: string;
  /** Severity labels in professional clinical view. */
  severityProfessional: {
    ok: string;
    caution: string;
    severe: string;
  };
  /** Severity labels in calm view (taker / adolescent / parent; never alarming). */
  severityCalm: {
    ok: string;
    caution: string;
    severe: string;
  };
}
