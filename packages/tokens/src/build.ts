/**
 * Builds dist/{company,ravanma}.css, dist/tokens.{js,d.ts}, dist/tokens.json and
 * dist/contrast.{md,json} from the DTCG sources via Style Dictionary (see sd.config.ts).
 *
 * Run: `pnpm tokens` (repo root) or `node src/build.ts` (this package).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { TransformedToken } from 'style-dictionary/types';
import { createDictionary, type Mode, type Theme } from '../sd.config.ts';
import { checkContrast, contrastMarkdown } from './contrast.ts';
import { cssName, type Tier, tierOf } from './naming.ts';

const DIST = fileURLToPath(new URL('../dist/', import.meta.url));
const HEADER = '/* Generated by @negaresh/tokens from the DTCG sources in tokens/. Do not edit. */';
const ALIAS = /^\{([^{}]+)\}$/;

export interface TokenEntry {
  /** Dot path in the DTCG source, e.g. `color.bg.canvas`. */
  path: string;
  /** CSS custom property, e.g. `--nds-bg-canvas`; null for primitives that are not emitted. */
  cssVar: string | null;
  type: string;
  tier: Tier;
  description?: string;
  /** Resolved CSS value per mode (equal for mode-independent tokens). */
  value: Record<Mode, string>;
  /** Source alias per mode, e.g. `color.sand.50`, when the token is an alias. */
  alias?: Partial<Record<Mode, string>>;
  /** Mode-dependent tokens are written in the light/dark blocks. */
  modal: boolean;
}

interface Resolved {
  path: string;
  token: TransformedToken;
}

async function resolve(theme: Theme, mode: Mode): Promise<Map<string, Resolved>> {
  const sd = createDictionary(theme, mode);
  const dict = await sd.getPlatformTokens('css');
  const map = new Map<string, Resolved>();
  for (const token of dict.allTokens) {
    const path = token.path.join('.');
    map.set(path, { path, token });
  }
  return map;
}

function aliasOf(token: TransformedToken): string | undefined {
  const original = token.original.$value;
  return typeof original === 'string' ? ALIAS.exec(original)?.[1] : undefined;
}

export async function collectTokens(theme: Theme): Promise<TokenEntry[]> {
  const light = await resolve(theme, 'light');
  const dark = await resolve(theme, 'dark');
  const entries: TokenEntry[] = [];

  for (const [path, { token }] of light) {
    const darkToken = dark.get(path)?.token ?? token;
    const name = cssName(token.path);
    const tier = tierOf(token.path, token.filePath);
    const value = { light: String(token.$value), dark: String(darkToken.$value) };
    const alias = { light: aliasOf(token), dark: aliasOf(darkToken) };

    // Theme/component tokens that alias an emitted token keep the reference, so a
    // later override of the primitive flows through (e.g. --nds-button-radius).
    const keepRef = (a: string | undefined) => {
      const target = a ? light.get(a)?.token : undefined;
      const targetName = target ? cssName(target.path) : null;
      return targetName && (tier === 'component' || tier === 'theme') && targetName !== name
        ? `var(--${targetName})`
        : undefined;
    };
    value.light = keepRef(alias.light) ?? value.light;
    value.dark = keepRef(alias.dark) ?? value.dark;

    const entry: TokenEntry = {
      path,
      cssVar: name ? `--${name}` : null,
      type: String(token.$type),
      tier,
      value,
      modal: tier === 'semantic' || value.light !== value.dark,
    };
    if (typeof token.$description === 'string') entry.description = token.$description;
    if (alias.light || alias.dark) {
      entry.alias = {};
      if (alias.light) entry.alias.light = alias.light;
      if (alias.dark) entry.alias.dark = alias.dark;
    }
    entries.push(entry);
  }
  return entries;
}

const decl = (e: TokenEntry, mode: Mode) => `  ${e.cssVar}:${e.value[mode]};`;

export function themeCss(entries: readonly TokenEntry[], note?: string): string {
  const emitted = entries.filter((e) => e.cssVar);
  const fixed = emitted.filter((e) => !e.modal);
  const modal = emitted.filter((e) => e.modal);
  const block = (mode: Mode) => modal.map((e) => decl(e, mode)).join('\n');
  return [
    HEADER,
    ...(note ? [`/* ${note} */`] : []),
    `:root{\n${fixed.map((e) => decl(e, 'light')).join('\n')}\n}`,
    `:root,[data-theme=light]{color-scheme:light;\n${block('light')}\n}`,
    `[data-theme=dark]{color-scheme:dark;\n${block('dark')}\n}`,
    `@media (prefers-color-scheme:dark){:root:not([data-theme]){color-scheme:dark;\n${block('dark')}\n}}`,
    '',
  ].join('\n');
}

/** Nested object of `var(--nds-*)` references, keyed by token path. */
export function tokenTree(entries: readonly TokenEntry[]): Record<string, unknown> {
  const root: Record<string, unknown> = {};
  for (const e of entries) {
    if (!e.cssVar) continue;
    const parts = e.path.split('.');
    let node = root;
    for (const part of parts.slice(0, -1)) {
      node[part] ??= {};
      node = node[part] as Record<string, unknown>;
    }
    node[parts.at(-1) as string] = `var(${e.cssVar})`;
  }
  return root;
}

export function tokensModule(entries: readonly TokenEntry[]): { js: string; dts: string } {
  const tree = JSON.stringify(tokenTree(entries), null, 2);
  const names = entries.filter((e) => e.cssVar).map((e) => JSON.stringify(e.cssVar));
  const banner = '// Generated by @negaresh/tokens. Do not edit.';
  return {
    js: [
      banner,
      '/** Token references as CSS variables, so light/dark and theme switches still apply. */',
      `export const tokens = Object.freeze(${tree});`,
      `export const cssVarNames = Object.freeze(${JSON.stringify(entries.filter((e) => e.cssVar).map((e) => e.cssVar))});`,
      '',
    ].join('\n'),
    dts: [
      banner,
      '/** Token references as CSS variables (`var(--nds-*)`), so light/dark and theme switches still apply. */',
      `export declare const tokens: ${tree.replaceAll(/"(var\([^"]+\))"/g, '"$1"')};`,
      `export type CssVarName = ${names.join(' | ')};`,
      'export declare const cssVarNames: readonly CssVarName[];',
      '',
    ].join('\n'),
  };
}

/** Semantic colour hex values per mode, keyed by path without `color.` (input to the contrast check). */
export function semanticColors(
  entries: readonly TokenEntry[],
): Record<Mode, Record<string, string>> {
  const out: Record<Mode, Record<string, string>> = { light: {}, dark: {} };
  for (const e of entries) {
    if (e.tier !== 'semantic' || e.type !== 'color') continue;
    const key = e.path.replace(/^color\./, '');
    out.light[key] = e.value.light;
    out.dark[key] = e.value.dark;
  }
  return out;
}

export async function build(): Promise<{ company: TokenEntry[] }> {
  mkdirSync(DIST, { recursive: true });
  const company = await collectTokens('company');
  const ravanma = await collectTokens('ravanma');

  writeFileSync(`${DIST}company.css`, themeCss(company));
  writeFileSync(
    `${DIST}ravanma.css`,
    themeCss(
      ravanma,
      'PLACEHOLDER: Ravanma theme = company semantics + Ravanma primitives. Values are re-measured before use (theme-ravanma README).',
    ),
  );
  const mod = tokensModule(company);
  writeFileSync(`${DIST}tokens.js`, mod.js);
  writeFileSync(`${DIST}tokens.d.ts`, mod.dts);
  writeFileSync(
    `${DIST}tokens.json`,
    `${JSON.stringify({ theme: 'company', modes: ['light', 'dark'], tokens: company }, null, 2)}\n`,
  );
  const contrast = checkContrast(semanticColors(company));
  writeFileSync(`${DIST}contrast.md`, contrastMarkdown(contrast, 'company'));
  writeFileSync(`${DIST}contrast.json`, `${JSON.stringify(contrast, null, 2)}\n`);
  return { company };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { company } = await build();
  console.log(`@negaresh/tokens: ${company.filter((e) => e.cssVar).length} CSS variables → dist/`);
}
