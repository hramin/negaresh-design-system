/**
 * WCAG 2.2 contrast checks for semantic colour pairs.
 * Pairs are ported from docs/foundations/contrast-report.md. Every new semantic colour
 * pair must be added here (CLAUDE.md §3).
 */
import { hexToRgb } from './values.ts';

export type PairUse =
  | 'text'
  | 'link'
  | 'text on selected'
  | 'button label'
  | 'ui'
  | 'control border'
  | 'focus'
  | 'status'
  | 'error text'
  | 'chart';

export interface ContrastPair {
  /** Foreground semantic token path, without the leading `color.` */
  fg: string;
  /** Background semantic token path, without the leading `color.` */
  bg: string;
  use: PairUse;
}

/** Text needs 4.5:1; UI components and graphics need 3:1 (WCAG 1.4.3, 1.4.11). */
export const MINIMUM: Record<PairUse, number> = {
  text: 4.5,
  link: 4.5,
  'text on selected': 4.5,
  'button label': 4.5,
  status: 4.5,
  'error text': 4.5,
  ui: 3,
  'control border': 3,
  focus: 3,
  chart: 3,
};

