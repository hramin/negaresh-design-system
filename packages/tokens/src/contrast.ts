function channel(c: number): number {
  const s = c / 255;
  return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

/** WCAG relative luminance of an opaque `#RRGGBB` colour. */
export function luminance(hex: string): number {
  const [r, g, b] = hexToRgb(hex);
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}

export function contrastRatio(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

export interface ContrastResult extends ContrastPair {
  mode: string;
  fgHex: string;
  bgHex: string;
  ratio: number;
  min: number;
  pass: boolean;
}

/**
 * @param modes resolved semantic colours per mode, keyed by path without `color.`
 *   (e.g. `{ light: { 'fg.default': '#1B1714' } }`)
 */
export function checkContrast(
  modes: Record<string, Record<string, string>>,
  pairs: readonly ContrastPair[] = PAIRS,
): ContrastResult[] {
  const out: ContrastResult[] = [];
  for (const [mode, colors] of Object.entries(modes)) {
    for (const pair of pairs) {
      const fgHex = colors[pair.fg];
      const bgHex = colors[pair.bg];
      if (!fgHex || !bgHex) {
        throw new Error(`Contrast pair ${pair.fg} on ${pair.bg}: token missing in ${mode} mode.`);
      }
      const ratio = contrastRatio(fgHex, bgHex);
      const min = MINIMUM[pair.use];
      // Compare at the reported precision so the table and the gate never disagree.
      out.push({
        ...pair,
        mode,
        fgHex,
        bgHex,
        ratio,
        min,
        pass: Math.floor(ratio * 100) / 100 >= min,
      });
    }
  }
  return out;
}

export function contrastMarkdown(results: readonly ContrastResult[], theme: string): string {
  const rows = results.map(
    (r) =>
      `| ${r.mode} | \`${r.fg}\` on \`${r.bg}\` | ${r.use} | ${r.ratio.toFixed(2)} | ${r.min} | ${r.pass ? 'pass' : '**FAIL**'} |`,
  );
  return [
    `# Contrast report — ${theme} theme`,
    '',
    'Generated by `pnpm tokens:check` from the token source. Do not edit by hand.',
    'WCAG 2.2: text 4.5:1, UI and graphics 3:1.',
    '',
    '| mode | pair | use | ratio | min | result |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}
